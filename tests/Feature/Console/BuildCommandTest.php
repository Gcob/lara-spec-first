/*
 * The generated tree goes to a temporary directory, and the namespaces written
 * into it are served by one autoloader registered for the whole file.
 *
 * That autoloader is doing what Composer does in a real application: PSR-4 maps
 * `App\Http\Generated\` to `app/Http/Generated/` there, and nothing here can rely
 * on that because the tree is not in this package's autoload map. A few lines of
 * `spl_autoload_register` buy the same thing without writing generated PHP into
 * the repository, which would then need a `.gitignore` entry of its own and would
 * survive an interrupted run.
 *
 * The namespace itself is fresh per test rather than fixed for the file, for the
 * reason {@see buildNamespace()} gives: a class this process has declared once
 * cannot be reloaded, so a fixed namespace would let one test's generated bytes
 * answer another test's assertions.
 */

/**
 * One temporary tree for this file, computed once.
 *
 * A function with a static rather than a property on the test case: Pest closures
 * are bound to the test instance at runtime but typed as a pending call, so state
 * hung on `$this` is invisible to static analysis. A named function says the same
 * thing and can be checked.
 */
function buildTree(): string
{
    static $tree = null;

    return $tree ??= sys_get_temp_dir().'/lsf-build-'.bin2hex(random_bytes(6));
}

/**
 * A fresh generated namespace for each test, and the reason is PHP rather than
 * tidiness.
 *
 * `beforeEach` deletes and rebuilds the tree at the same paths, but a class this
 * process has already declared stays declared: PHP will not autoload a second
 * definition, and it tracks includes by path. So a fixed namespace would mean
 * every test after the first one to load a controller asserting against the bytes
 * *that* build wrote — silently, and correctly, for as long as every test builds
 * from the same fixture. A namespace nobody has loaded yet cannot be stale.
 *
 * Passing a value sets it; passing nothing reads it back.
 */
function buildNamespace(?string $fresh = null): string
{
    static $namespace = null;

    if ($fresh !== null) {
        $namespace = $fresh;
    }

    return $namespace ??= 'LsfBuild'.bin2hex(random_bytes(4));
}

beforeAll(function (): void {
    $tree = buildTree();

    // Registered on the root the per-test namespaces share, since the namespace
    // this maps from is not known yet when this runs. Everything after the first
    // separator is the path under the tree, which is the same rule Composer's
    // PSR-4 applies in a real application.
    spl_autoload_register(static function (string $class) use ($tree): void {
        if (! str_starts_with($class, 'LsfBuild')) {
            return;
        }

        $separator = strpos($class, '\\');

        if ($separator === false) {
            return;
        }

        $file = $tree.'/'.str_replace('\\', '/', substr($class, $separator + 1)).'.php';

        if (is_file($file)) {
            require $file;
        }
    });
});

beforeEach(function (): void {
    // Each test starts from an empty tree, so what one of them wrote can never
    // be what another one asserts.
    exec('rm -rf '.escapeshellarg(buildTree()));

    config()->set(GeneratedRoutesLocator::SETTING, buildTree());
    config()->set('lara-spec-first.generated.namespace', buildNamespace('LsfBuild'.bin2hex(random_bytes(4))));
    config()->set('lara-spec-first.spec.path', specFixturePath('operations.yaml'));
});

afterAll(function (): void {
    exec('rm -rf '.escapeshellarg(buildTree()));
});

function build(): int
{
    return app(Kernel::class)->call('spec:build');
}

/**
 * @return list<string> every path under the generated tree, relative to it
 */
function treeContents(string $root): array
{
    if (! is_dir($root)) {
        return [];
    }

    $found = [];

    /** @var iterable<SplFileInfo> $entries */
    $entries = new RecursiveIteratorIterator(
        new RecursiveDirectoryIterator($root, RecursiveDirectoryIterator::SKIP_DOTS),
    );

    foreach ($entries as $entry) {
        // Normalized to `/` rather than left as the platform's separator, because
        // every caller compares against a path the generator writes — and the
        // generator writes `Controllers/` on every platform.
        $found[] = str_replace(DIRECTORY_SEPARATOR, '/', substr($entry->getPathname(), strlen($root) + 1));
    }

    sort($found);

    return $found;
}

it('emits one controller per operation and the routes file', function (): void {
    expect(build())->toBe(0)
        ->and(treeContents(buildTree()))->toBe([
            'Controllers/CreatePostController.php',
            'Controllers/DeleteUsersIdController.php',
            'Controllers/ShowCurrentUserController.php',
            'Controllers/ShowUserController.php',
            GeneratedRoutesLocator::FILE,
        ]);
});

// The fixture declares `delete /users/{id}` without an `operationId`, which is
// what makes it worth building against: the derived name and the declared one
// have to come out of the same run.
it('names a controller from the operationId, or from the method and path', function (): void {
    build();

    expect(is_file(buildTree().'/Controllers/ShowUserController.php'))->toBeTrue()
        ->and(is_file(buildTree().'/Controllers/DeleteUsersIdController.php'))->toBeTrue();
});

/*
 * The adversarial half. `hostile-paths.yaml` is entirely valid OpenAPI and
 * entirely hostile to a generator that builds PHP by concatenating strings: a
 * document is data, a generated file is code, and the boundary between them is
 * where injection lives.
 *
 * The guard for this already existed — `emits PHP that parses` runs `php -l` over
 * everything emitted. What was missing was a fixture that attacks it. That is the
 * general lesson: a test only covers the inputs somebody thought to write down.
 */

function buildHostile(): int
{
    config()->set('lara-spec-first.spec.path', specFixturePath('hostile-paths.yaml'));

    return build();
}

it('emits PHP that parses from a contract written to break it', function (): void {
    expect(buildHostile())->toBe(0);

    foreach (treeContents(buildTree()) as $relative) {
        exec('php -l '.escapeshellarg(buildTree().'/'.$relative), $output, $status);

        expect($status)->toBe(0, $relative.' does not parse: '.implode("\n", $output));
    }
});

// Worse than a parse error, and the reason this fixture exists. A value closing a
// block comment ends the docblock early, turns what follows into a statement, and
// lets the docblock's own closing delimiter reopen and close a comment around the
// rest — so the file parses, loads, and runs whatever the document put there.
// Verified by side effect rather than by reading the output, because that is what
// an attacker would use.
it('executes nothing a contract smuggled into a docblock', function (): void {
    $witness = sys_get_temp_dir().'/lsf-injected';
    @unlink($witness);

    buildHostile();

    foreach (treeContents(buildTree()) as $relative) {
        if (str_ends_with($relative, '.php') && str_contains($relative, 'Controllers/')) {
            require buildTree().'/'.$relative;
        }
    }

    expect(is_file($witness))->toBeFalse('a generated file executed code from the specification');
});

it('routes a path a naive literal would have broken', function (): void {
    buildHostile();

    require buildTree().'/'.GeneratedRoutesLocator::FILE;

    $response = app(HttpKernel::class)->handle(Request::create("/users/o'brien"));

    expect($response->getStatusCode())->toBe(501);
});

