// `changedNothing()` is what makes idempotence legible from the outside, so the
// command says it in words rather than leaving a reader to notice that every
// count came back zero.
it('says it changed nothing when a second run changes nothing', function (): void {
    build();

    $output = new BufferedOutput;
    app(Kernel::class)->call('spec:build', [], $output);

    expect($output->fetch())->toContain('Already up to date.');
});

// The invariant, checked where a consumer would feel it: the build owns its own
// directory and nothing else, so a file beside the tree is untouched.
it('writes nothing outside the tree it owns', function (): void {
    $neighbour = dirname(buildTree()).'/lsf-neighbour-'.bin2hex(random_bytes(4));
    mkdir($neighbour, 0o777, true);
    file_put_contents($neighbour.'/untouched.php', 'kept');

    try {
        build();

        expect(scandir($neighbour))->toBe(['.', '..', 'untouched.php'])
            ->and(file_get_contents($neighbour.'/untouched.php'))->toBe('kept');
    } finally {
        exec('rm -rf '.escapeshellarg($neighbour));
    }
});

// The property that keeps idempotence true in a real project rather than only in
// a test. Almost every Laravel application formats its code, and `phpdoc_separation`
// ships in both Pint's Laravel preset and php-cs-fixer's defaults — so output that
// is not already canonical under it would be rewritten by the consumer's formatter
// and rewritten back by the next build, forever. Emitting the canonical form is
// what stops the two from fighting.
it('emits output a formatter finds nothing to change in', function (): void {
    build();

    exec(
        'vendor/bin/pint --test '.escapeshellarg(buildTree()).' 2>&1',
        $output,
        $status,
    );

    expect($status)->toBe(0, "Pint would rewrite generated output:\n".implode("\n", $output));
});

// Every file, rather than a sample of one. The norm is emitted unconditionally,
// so the assertion that matches it is one that fails the moment a new kind of
// generated file arrives without it — which is exactly how a convention that
// lives in prose erodes. What each part has to say is asserted at the emitters,
// in tests/Unit/Generation/; what is proven here is that the real command puts it
// in everything it writes.
// A 3.1 document may legally carry only `webhooks`, and zero routes is an outcome
// rather than an error. The file is still written — it is what replaces the routes
// a previous build registered — and it is held to the same promise as any other
// generated file: a formatter finds nothing to change in it. It used to fail that,
// on `single_line_after_imports` and `single_blank_line_at_eof`, over an empty
// registration block nobody could see.
it('writes a routes file a formatter accepts when the contract routes nothing', function (): void {
    config()->set('lara-spec-first.spec.path', specFixturePath('openapi-3.1-webhooks-only.yaml'));

    expect(build())->toBe(0)
        ->and(treeContents(buildTree()))->toBe([GeneratedRoutesLocator::FILE]);

    exec('vendor/bin/pint --test '.escapeshellarg(buildTree()).' 2>&1', $output, $status);

    $contents = (string) file_get_contents(buildTree().'/'.GeneratedRoutesLocator::FILE);

    expect($status)->toBe(0, "Pint would rewrite generated output:\n".implode("\n", $output))
        ->and($contents)->toContain('No operation, so this file registers none')
        ->and($contents)->not->toContain('Every controller imported below');
});

// And it still boots: the provider loads the file, and an application with no
// generated route is not an application that fails to start.
it('registers no route from a contract that routes nothing', function (): void {
    config()->set('lara-spec-first.spec.path', specFixturePath('openapi-3.1-webhooks-only.yaml'));
    build();

    require buildTree().'/'.GeneratedRoutesLocator::FILE;

    $generated = array_filter(
        app('router')->getRoutes()->getRoutes(),
        static fn (Route $route): bool => str_contains($route->getActionName(), 'routeAction'),
    );

    expect($generated)->toBe([]);
});

it('carries provenance, findings and navigation into every file it writes', function (): void {
    build();

    $files = treeContents(buildTree());
    $missing = [];

    foreach ($files as $relative) {
        $contents = (string) file_get_contents(buildTree().'/'.$relative);

        foreach ([GeneratedFile::MARKER, 'Provenance', 'Findings', 'Navigation'] as $part) {
            if (! str_contains($contents, $part)) {
                $missing[] = $relative.' carries no '.$part;
            }
        }
    }

    expect($files)->not->toBeEmpty()
        ->and($missing)->toBe([]);
});

// The pointer is what rename detection will compare, so every controller carries
// one rather than most of them.
it('carries the position it came from in every controller it writes', function (): void {
    build();

    $withoutPointer = array_values(array_filter(
        treeContents(buildTree()),
        static fn (string $relative): bool => str_starts_with($relative, 'Controllers/')
            && ! str_contains((string) file_get_contents(buildTree().'/'.$relative), '#/paths/'),
    ));

    expect($withoutPointer)->toBe([])
        ->and(file_get_contents(buildTree().'/Controllers/ShowUserController.php'))
        ->toContain('#/paths/~1users~1{id}/get');
});

// Named from the project root, and asserted as the absence of the alternative.
// A generated file may be committed — that is the consumer's `.gitignore` choice,
// not ours — and an absolute path in a repository differs between every developer
// and every CI runner, which is a diff nobody made and one machine's directory
// layout published.
it('names its source from the project root rather than absolutely', function (): void {
    build();

    $absolute = [];

    foreach (treeContents(buildTree()) as $relative) {
        $contents = (string) file_get_contents(buildTree().'/'.$relative);

        if (! str_contains($contents, 'tests/Fixtures/operations.yaml')) {
            $absolute[] = $relative.' does not name the specification';
        }

        if (str_contains($contents, dirname(__DIR__, 3))) {
            $absolute[] = $relative.' names it absolutely';
        }
    }

    expect($absolute)->toBe([]);
});

// The two-class seam, asserted on the classes rather than on the text that
// produced them: `final` for as long as nothing may extend a generated
// controller, one shipped base for every operation, and one declared method so
// the routes file can name it as a plain string.
//
// DECISION: the emitter's own tests assert these three properties on the emitted
// text, and this test asserts them again on what PHP loaded. The overlap is
// deliberate rather than an oversight — the failure modes differ. Text that reads
// `final class` and a class PHP reports as final are the same claim only while
// nothing between them is wrong: the planner could route to a class the emitter
// never wrote, and a `use` this file resolves differently would change the parent
// without changing a byte of the emitter's output. Do not delete either copy as a
// duplicate.
// The fixture this file builds from declares no `x-controller`, which is what makes
// `final` the expected answer for every class in it. The other branch is asserted
// above, from a fixture that declares one.
it('generates a final controller over the shipped base, carrying one routeAction', function (): void {
    build();

    $controllers = array_values(array_filter(
        treeContents(buildTree()),
        static fn (string $relative): bool => str_starts_with($relative, 'Controllers/'),
    ));

    $expected = array_map(
        static fn (string $relative): string => buildNamespace().'\\Controllers\\'.basename($relative, '.php'),
        $controllers,
    );

    // Loaded through the registered autoloader, the way an application reaches
    // them, rather than by requiring the files: what is under test includes the
    // class landing where its namespace says it does.
    foreach ($expected as $class) {
        expect(class_exists($class))->toBeTrue($class.' does not autoload');
    }

    // Reached through what PHP has actually loaded rather than by naming a class
    // from a filename: this is the same list, and it is a list of loaded classes
    // rather than of strings that look like ones.
    $loaded = array_values(array_intersect(get_declared_classes(), $expected));

    expect($expected)->not->toBeEmpty()
        ->and($loaded)->toHaveCount(count($expected));

    foreach ($loaded as $class) {
        $reflection = new ReflectionClass($class);
        $parent = $reflection->getParentClass();
        $declared = array_map(
            static fn (ReflectionMethod $method): string => $method->getName(),
            array_filter(
                $reflection->getMethods(),
                static fn (ReflectionMethod $method): bool => $method->getDeclaringClass()->getName() === $class,
            ),
        );

        expect($reflection->isFinal())->toBeTrue($class.' is not final')
            ->and($parent === false ? null : $parent->getName())->toBe(SpecController::class)
            ->and(array_values($declared))->toBe(['routeAction']);
    }
});

/*
 * The two-class seam, through the real command. What a unit test cannot say here is
 * that the pieces agree: the class the emitter writes, the target the routes file
 * registers, and the answer the autoloader gave about the child are three
 * decisions taken in three classes from one fact.
 *
 * The fixture's first operation names a class this repository really autoloads and
 * its second names one nothing has written, so both branches come out of one run.
 */

function buildCustomControllers(): int
{
    config()->set('lara-spec-first.spec.path', specFixturePath('custom-controllers.yaml'));

    return build();
}

